#!/usr/bin/env python3
"""Throttling TCP proxy: make one browser tab a slow client, for demos.

The proxy sits between browser tabs and the server and passes each
connection's server->client bytes on at a rate you choose, so a throttled tab
is slow on the network: real TCP backpressure, late pongs, and flow control
kicking in on the server, while the other tabs stay fast. Nothing is parsed;
bytes are relayed as they are. Not part of the evaluated server.

Usage (the browser client connects to 8765, so the server moves to 8767):
    python solution_server.py --port 8767
    python tools/slow_proxy.py --listen 8765 --target 8767
    python caption_source.py --uri ws://127.0.0.1:8767 --duration 120

Then open two tabs at http://127.0.0.1:8000. Commands, typed into the proxy
while it runs (rates are bytes/s from server to client, 0 = unthrottled):
    list            show connections and their rates
    <id> <rate>     set one connection's rate, e.g. "2 400"
    all <rate>      set every connection's rate and the default for new ones

With WebSocket compression a caption is only ~30-50 bytes on the wire, and the
public source's full stream (all revisions) needs ~150-200 bytes/s:
  200 B/s  barely lags (measured)
  100 B/s  falls a few seconds behind, then flow control sends finals only (measured)
   50 B/s  about what finals alone need, so even finals fall behind (estimate)

Generated by claude
"""

import argparse
import asyncio
import sys
import time

CHUNK = 256  # forward at most this many bytes at a time when throttled


class Conn:
    def __init__(self, conn_id: int, rate: float):
        self.id = conn_id
        self.rate = rate          # bytes/s server->client, 0 = unthrottled
        self.tokens = 0.0
        self.tokens_t = time.monotonic()
        self.sent = 0

    async def take(self, n: int) -> None:
        """Wait until n bytes may be forwarded at this connection's rate."""
        while self.rate > 0:
            now = time.monotonic()
            # Allow at most one second's worth of burst (or one chunk, if the
            # rate is below a chunk per second, so a chunk can always go).
            cap = max(self.rate, n)
            self.tokens = min(cap, self.tokens + (now - self.tokens_t) * self.rate)
            self.tokens_t = now
            if self.tokens >= n:
                self.tokens -= n
                return
            await asyncio.sleep((n - self.tokens) / self.rate)


conns: dict[int, Conn] = {}
next_id = 1
default_rate = 0.0


async def pipe(reader: asyncio.StreamReader, writer: asyncio.StreamWriter,
               conn: Conn | None) -> None:
    """Copy bytes reader -> writer, throttled by conn if given."""
    try:
        while True:
            # Throttled: forward about 10 small pieces a second, so data trickles
            # in at the rate instead of arriving in bursts of a whole chunk.
            throttled = conn is not None and conn.rate > 0
            data = await reader.read(max(1, min(CHUNK, int(conn.rate / 10))) if throttled else 65536)
            if not data:
                break
            if conn:
                await conn.take(len(data))
                conn.sent += len(data)
            writer.write(data)
            await writer.drain()
    except (ConnectionError, asyncio.CancelledError):
        pass
    finally:
        writer.close()


async def handle(client_reader, client_writer, target_host: str, target_port: int) -> None:
    global next_id
    conn = Conn(next_id, default_rate)
    next_id += 1
    try:
        # A small read buffer, so data waits in the server's socket (where the
        # server feels the backpressure) instead of piling up in the proxy.
        server_reader, server_writer = await asyncio.open_connection(
            target_host, target_port, limit=4096)
    except OSError as e:
        print(f"[{conn.id}] cannot reach server: {e}", flush=True)
        client_writer.close()
        return
    conns[conn.id] = conn
    print(f"[{conn.id}] connected, rate={describe(conn.rate)}", flush=True)
    await asyncio.gather(
        pipe(server_reader, client_writer, conn),   # server -> client: throttled
        pipe(client_reader, server_writer, None),   # client -> server: as is
    )
    conns.pop(conn.id, None)
    print(f"[{conn.id}] disconnected after {conn.sent} bytes", flush=True)


def describe(rate: float) -> str:
    return "unthrottled" if rate <= 0 else f"{rate:.0f} B/s"


def on_command(line: str) -> None:
    global default_rate
    parts = line.split()
    try:
        if parts == ["list"]:
            for c in conns.values():
                print(f"[{c.id}] rate={describe(c.rate)} sent={c.sent} bytes", flush=True)
            if not conns:
                print("no connections", flush=True)
        elif len(parts) == 2 and parts[0] == "all":
            default_rate = float(parts[1])
            for c in conns.values():
                c.rate = default_rate
            print(f"all connections and new ones: {describe(default_rate)}", flush=True)
        elif len(parts) == 2:
            conn = conns[int(parts[0])]
            conn.rate = float(parts[1])
            print(f"[{conn.id}] rate={describe(conn.rate)}", flush=True)
        elif parts:
            print("commands: list | <id> <rate> | all <rate>", flush=True)
    except (KeyError, ValueError):
        print("unknown connection id or bad number", flush=True)


async def main() -> None:
    global default_rate
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--listen", type=int, default=8765, help="port browser tabs connect to")
    p.add_argument("--target", type=int, default=8767, help="port the server listens on")
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--rate", type=float, default=0,
                   help="default bytes/s for new connections (0 = unthrottled)")
    args = p.parse_args()
    default_rate = args.rate

    server = await asyncio.start_server(
        lambda r, w: handle(r, w, args.host, args.target), args.host, args.listen)
    loop = asyncio.get_running_loop()
    loop.add_reader(sys.stdin, lambda: on_command(sys.stdin.readline()))
    print(f"proxy :{args.listen} -> :{args.target}, default rate {describe(default_rate)}", flush=True)
    print("commands: list | <id> <rate> | all <rate>", flush=True)
    async with server:
        await server.serve_forever()


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        pass
